    /** 汉字 -> 拼音首字母（运行时解析 RAW + RAW2 构建） */
    private val PINYIN_MAP: Map<Char, Char> by lazy {
        val map = LinkedHashMap<Char, Char>()
        for (group in (RAW + "|" + RAW2).split('|')) {
            if (group.isEmpty()) continue
            val initial = group[0]
            for (i in 1 until group.length) {
                map[group[i]] = initial
            }
        }
        map
    }

    fun pinyinInitialOf(ch: Char): Char? = PINYIN_MAP[ch]

    /**
     * 把 label 转成搜索键：
     * 中文逐字取拼音首字母；ASCII 字母直接计入；其余忽略。
     * 返回 (首字母串, 首字母串, 原名小写) —— 首字母串同时充当「全拼/首字母」两用。
     */
    fun buildSearchKeys(label: String): Triple<String, String, String> {
        val initials = StringBuilder()
        for (ch in label) {
            val lower = ch.lowercaseChar()
            if (lower in 'a'..'z') {
                initials.append(lower)
            } else {
                val py = PINYIN_MAP[ch]
                if (py != null) initials.append(py)
            }
        }
        val labelLower = label.lowercase()
        return Triple(initials.toString(), initials.toString(), labelLower)
    }

    /** 把字母串按 T9 表转成数字串（非字母字符原样保留） */
    fun toT9(s: String): String {
        val sb = StringBuilder(s.length)
        for (ch in s) {
            sb.append(T9_MAP[ch] ?: ch)
        }
        return sb.toString()
    }

    /**
     * 在已构建好搜索键的列表中做模糊（子串）匹配。
     * @param query 当前输入（QWERTY=字母串，T9=数字串）
     * @param isT9 是否 T9 模式
     * @return 命中的条目（保持原顺序）
     */
    fun match(entries: List<AppSearchEntry>, query: String, isT9: Boolean): List<AppSearchEntry> {
        if (query.isEmpty()) return entries
        val q = query.lowercase()
        return entries.filter { e ->
            val candidates = if (isT9) {
                listOf(toT9(e.pinyinInitials), toT9(e.labelLower))
            } else {
                listOf(e.pinyinInitials, e.labelLower)
            }
            // 子串匹配：不只从首字符，任意位置命中即可
            candidates.any { it.contains(q) }
        }
    }
